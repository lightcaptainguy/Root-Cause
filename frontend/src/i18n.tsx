export function translate(text:string, language:Language):string {
 if(language==='en') return text;
 if(HINDI[text]) return HINDI[text];
 if(text.startsWith('Classifier suggests ') && text.endsWith('; verify the image and seek qualified assessment')) {
  const label=text.slice('Classifier suggests '.length, -'; verify the image and seek qualified assessment'.length);
  return 'मॉडल का अनुमान: '+(HINDI[label] || label)+'। चित्र जाँचें और योग्य विशेषज्ञ की राय लें।';
 }
 return text.split(' · ').map(part=>HINDI[part] || part).join(' · ');
}
const Context=createContext({language:'en' as Language,locale:'en-IN',setLanguage:(_value:Language)=>{},t:(text:string)=>text});
export function LanguageProvider({children}:{children:ReactNode}) {
 const [language,setLanguage]=useState<Language>(()=>{try{return localStorage.getItem('root-cause-language')==='hi'?'hi':'en';}catch{return 'en';}});
 useEffect(()=>{document.documentElement.lang=language;document.title=language==='hi'?'Root-Cause — फसल की स्थिति':'Root-Cause';try{localStorage.setItem('root-cause-language',language);}catch{}},[language]);
 return <Context.Provider value={{language,locale:language==='hi'?'hi-IN':'en-IN',setLanguage,t:text=>translate(text,language)}}>{children}</Context.Provider>;
}
export const useI18n=()=>useContext(Context);
